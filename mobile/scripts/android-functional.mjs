import {_android as android,expect} from '@playwright/test';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {execFileSync} from 'node:child_process';
const root=resolve('..'),serial='emulator-5580',pkg='top.nullsf.gpuchecker';
const device=(await android.devices()).find(d=>d.serial()===serial);if(!device)throw Error('Start GPUChecker_Test_API30 emulator first');
device.setDefaultTimeout(15000);const reports=[];
const events=async()=>JSON.parse(await readFile(resolve(root,'build/mobile-ssh-events.json'),'utf8').catch(()=>'{}'));
let page=await(await device.webView({pkg})).page();
const state=()=>page.evaluate(()=>window.Capacitor.Plugins.GpuMonitor.getState());
async function poll(fn,message){for(let i=0;i<80;i++){if(await fn())return;await new Promise(r=>setTimeout(r,250))}throw Error(message)}
const baseEvents=await events();await writeFile(resolve(root,'build/mobile-ssh-control.json'),JSON.stringify({mode:'gpu'}));
try{
 await page.getByRole('button',{name:'添加主机',exact:true}).click();
 await page.getByLabel('显示名称',{exact:true}).fill('EMULATOR · SSH');
 await page.getByLabel('主机地址',{exact:true}).fill('10.0.2.2');await page.getByLabel('用户名',{exact:true}).fill('mobile-test');await page.getByLabel('端口',{exact:true}).fill('41722');
 await page.getByRole('button',{name:'安全配置认证'}).click();
 await device.fill({clazz:'android.widget.EditText'},'mobile-test-only');await device.tap({res:'android:id/button1'});
 await device.wait({text:'核对 SSH 主机指纹'});
 const before=await events();expect(before.passwordAttempts??0).toBe(baseEvents.passwordAttempts??0);
 await device.tap({res:'android:id/button1'});
 await poll(async()=>Object.values((await state()).runtimes).some(r=>r.fresh),'SSH did not receive a native sample');
 const current=await state(),host=current.hosts.find(h=>h.name==='EMULATOR · SSH');expect(host.credentialReady).toBe(true);
 expect(current.runtimes[host.id].snapshot.gpus.map(g=>g.index)).toEqual([0,2]);
 expect(current.runtimes[host.id].snapshot.processes[0].cwd).toBe('/home/mobile-test/experiments/read-only');
 const after=await events();expect(after.passwordAccepted).toBeGreaterThan(0);expect(after.probeVerified).toBeGreaterThan(0);
 expect(JSON.stringify(current)).not.toContain('mobile-test-only');
 const storage=await page.evaluate(()=>JSON.stringify(localStorage));expect(storage).not.toContain('mobile-test-only');
 const prefs=execFileSync('adb',['-s',serial,'shell','run-as',pkg,'cat','shared_prefs/encrypted_credentials.xml'],{encoding:'utf8'});expect(prefs).not.toContain('mobile-test-only');
 reports.push('Real native SSH password authentication, trust-before-auth, exact desktop probe, native GPU indices, process details, and credential isolation passed.');
 await new Promise(r=>setTimeout(r,6500));
 const history=await page.evaluate(async id=>window.Capacitor.Plugins.GpuMonitor.history({id,start:Date.now()-3600000,end:Date.now()}),host.id);expect(history.rows.length).toBeGreaterThan(0);
 await page.getByRole('button',{name:'暂停',exact:true}).click();
 await poll(async()=>!(await state()).hosts.find(h=>h.id===host.id).autoconnect,'Pause did not persist');
 expect((await state()).runtimes[host.id].snapshot.gpus.length).toBe(2);
 await page.screenshot({path:resolve(root,'build/mobile-android-paused.png')});
 execFileSync('adb',['-s',serial,'shell','am','force-stop',pkg]);execFileSync('adb',['-s',serial,'shell','am','start','-n',pkg+'/.MainActivity']);await new Promise(r=>setTimeout(r,1200));
 page=await(await device.webView({pkg})).page();await expect(page.locator('.host-tile')).toHaveCount(1);
 const restored=await state();expect(restored.hosts[0].autoconnect).toBe(false);expect(restored.runtimes[host.id].snapshot.gpus.length).toBe(2);
 await page.getByRole('button',{name:'恢复',exact:true}).click();await poll(async()=>(await state()).runtimes[host.id]?.fresh,'Saved password did not reconnect');
 reports.push('SQLite history, pause, frozen snapshot, process restart, persisted host and native saved-password reconnect passed.');
 await writeFile(resolve(root,'build/mobile-ssh-control.json'),JSON.stringify({mode:'cpu'}));
 await poll(async()=>(await state()).runtimes[host.id]?.snapshot?.gpu_status==='no_gpu','No-GPU frame did not arrive');
 expect((await state()).runtimes[host.id].fresh).toBe(true);
 await writeFile(resolve(root,'build/mobile-ssh-control.json'),JSON.stringify({mode:'gpu'}));
 await poll(async()=>(await state()).runtimes[host.id]?.snapshot?.gpus.length===2,'GPU view did not return');
 reports.push('No-GPU SSH continuity and return to GPU monitoring passed.');
 await page.screenshot({path:resolve(root,'build/mobile-android-live.png')});
 await writeFile(resolve(root,'build/mobile-android-functional-report.json'),JSON.stringify({passed:reports,hostId:host.id,events:await events()},null,2));
 console.log(reports.join('\n'));
}catch(error){console.error(error);process.exitCode=1}finally{await Promise.race([device.close().catch(()=>{}),new Promise(resolve=>setTimeout(resolve,5000))]);process.exit(process.exitCode??0)}
